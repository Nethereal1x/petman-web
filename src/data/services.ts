import type { Member } from './team';

export type PriceRow = {
  name: string;
  /** число в гривнях або готовий текст для діапазонів («900–1 200») */
  price: number | string;
  from?: boolean;
  note?: string;
};

export type PriceGroup = {
  title: string;
  note?: string;
  rows: PriceRow[];
};

export type Service = {
  slug: string;
  /** коротка назва для меню та списків */
  name: string;
  /** H1 сторінки */
  title: string;
  metaTitle: string;
  metaDescription: string;
  /** один рядок для списку послуг */
  summary: string;
  lead: string;
  image:
    | 'svc-therapy'
    | 'svc-vaccination'
    | 'svc-dentistry'
    | 'svc-lab'
    | 'svc-surgery'
    | 'svc-checkup'
    | 'clinic-reception'
    | 'clinic-cat';
  imageAlt: string;
  /** мінімальна ціна для списків; null, якщо ціну називають за телефоном */
  from: number | null;
  fromLabel?: string;
  prices: PriceGroup[];
  priceNote?: string;
  points: { title: string; text: string }[];
  faq: { q: string; a: string }[];
  /** хто з команди веде напрям (за id з team.ts) */
  doctors: Member['id'][];
  related: string[];
  /** акція: показується лише разом зі строком дії */
  promo?: { regular: number; price: number; until: string | null };
  includes?: string[];
  /** магазин, а не медична послуга: без запису, FAQ і прайсу, з посиланням на Instagram */
  shop?: boolean;
};

